/** "de" or "en" for a Home Assistant language code. */
export function langOf(language) {
  return String(language || "").toLowerCase().startsWith("en") ? "en" : "de";
}

/** Websocket error -> display text; known codes are translated. */
export function errorText(err, t) {
  if (err && err.code === "lamp_rejected") return t("err_lamp_rejected");
  return (err && (err.message || err.code)) || String(err);
}

/** Translator bound to a Home Assistant language code. */
export function translator(language) {
  const table = STRINGS[langOf(language)];
  return (key) => table[key] ?? STRINGS.de[key] ?? key;
}
